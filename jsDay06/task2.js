let arr1 = [0,1, 2, 3, 4]
console.log(arr1);
// console.log(arr1[0]);
// console.log(arr1[arr1.length-1]);

// push method to add a new number to the end of the array and log the updated array.
arr1.push(6);        
console.log(arr1);

// pop method to remove the last element from the array and log the updated array.
arr1.pop();
console.log(arr1);

// shift method to remove the first element from the array and log the updated array.
arr1.shift()
console.log(arr1);

// unshift method to add a new number to the beginning of the array and log the updated array
arr1.unshift(0);
console.log(arr1);
